import {writeFileSync} from 'node:fs';
import {LEVELS} from '../src/levels';
import {rulesFingerprint,sha256} from './replay-archive';
import {taskFingerprint} from './task-fingerprint';
writeFileSync('src/daily-fingerprints.ts','// Generated by npm run fingerprints; tests reject stale fingerprints.\nexport const DAILY_FINGERPRINTS='+JSON.stringify({rules:rulesFingerprint(),tasks:taskFingerprint(),levels:Object.fromEntries(LEVELS.map(l=>[l.id,sha256(JSON.stringify(l))]))},null,2)+' as const;\n');
